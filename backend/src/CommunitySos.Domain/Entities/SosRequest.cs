using CommunitySos.Domain.Common;
using CommunitySos.Domain.Enums;
using CommunitySos.Domain.ValueObjects;
using NetTopologySuite.Geometries;

namespace CommunitySos.Domain.Entities;

/// <summary>
/// Aggregate root for an emergency request. All status changes go through <see cref="TransitionTo"/>,
/// which enforces the state machine and appends to <see cref="StatusHistory"/>.
/// Who may perform an action (assigned admin, Master Admin, requester) is checked by the application layer.
/// </summary>
public sealed class SosRequest : Entity<Guid>, IHasTimestamps, IAuditedEntity
{
    public const int DescriptionMaxLength = 1000;
    public const int RemarksMaxLength = 500;
    public const int AddressMaxLength = 500;
    public const int ReferenceNoMaxLength = 20;
    public const int MaxAttachments = 5;

    /// <summary>Allow for queued/offline submissions and device clock drift.</summary>
    public static readonly TimeSpan MaxCaptureAge = TimeSpan.FromMinutes(30);
    public static readonly TimeSpan MaxFutureSkew = TimeSpan.FromMinutes(5);

    private static readonly Dictionary<SosStatus, SosStatus[]> AllowedTransitions = new()
    {
        [SosStatus.Pending] = [SosStatus.Approved, SosStatus.Rejected, SosStatus.Cancelled, SosStatus.Escalated, SosStatus.Expired],
        [SosStatus.Escalated] = [SosStatus.Approved, SosStatus.Rejected, SosStatus.Cancelled, SosStatus.Expired],
        [SosStatus.Approved] = [SosStatus.Resolved, SosStatus.Cancelled, SosStatus.Expired],
    };

    private readonly List<SosAttachment> _attachments = [];
    private readonly List<SosStatusHistory> _statusHistory = [];

    private SosRequest()
    {
    }

    /// <summary>Database sequence value; <see cref="ReferenceNo"/> is computed from it (e.g. SOS-00000123).</summary>
    public long ReferenceSeq { get; private set; }

    public string ReferenceNo { get; private set; } = null!;

    /// <summary>Idempotency key generated by the app; a retried submit returns the existing SOS.</summary>
    public Guid ClientRequestId { get; private set; }

    public Guid RequesterUserId { get; private set; }

    public User? Requester { get; private set; }

    /// <summary>Admin responsible for review (the requester's referrer, or the Master Admin as fallback).</summary>
    public Guid AssignedAdminId { get; private set; }

    public User? AssignedAdmin { get; private set; }

    public SosCategory Category { get; private set; }

    public string? Description { get; private set; }

    public Point Location { get; private set; } = null!;

    public decimal Latitude { get; private set; }

    public decimal Longitude { get; private set; }

    public double? AccuracyMeters { get; private set; }

    public string? Address { get; private set; }

    public DateTime ClientCapturedAt { get; private set; }

    public SosStatus Status { get; private set; }

    public bool IsAutoApproved { get; private set; }

    public DateTime? EscalatedAt { get; private set; }

    public Guid? ReviewedByUserId { get; private set; }

    public User? ReviewedBy { get; private set; }

    public DateTime? ReviewedAt { get; private set; }

    public string? ReviewRemarks { get; private set; }

    public int RecipientCount { get; private set; }

    public DateTime? ClosedAt { get; private set; }

    public DateTime CreatedAt { get; private set; }

    public DateTime UpdatedAt { get; private set; }

    public byte[] RowVersion { get; private set; } = [];

    public IReadOnlyCollection<SosAttachment> Attachments => _attachments.AsReadOnly();

    public IReadOnlyCollection<SosStatusHistory> StatusHistory => _statusHistory.AsReadOnly();

    public bool IsAwaitingReview => Status is SosStatus.Pending or SosStatus.Escalated;

    public bool IsOpen => IsAwaitingReview || Status == SosStatus.Approved;

    public GeoCoordinate Coordinate => GeoCoordinate.FromPoint(Location);

    public static SosRequest Create(
        User requester,
        Guid assignedAdminId,
        Guid clientRequestId,
        SosCategory category,
        string? description,
        GeoCoordinate location,
        double? accuracyMeters,
        DateTime clientCapturedAt,
        DateTime now)
    {
        ArgumentNullException.ThrowIfNull(requester);

        if (!requester.IsActive)
        {
            throw new DomainException("user.inactive", "Account is not active.");
        }

        if (clientRequestId == Guid.Empty)
        {
            throw new DomainException("sos.client_request_id_required", "A client request id is required.");
        }

        if (assignedAdminId == Guid.Empty)
        {
            throw new DomainException("sos.no_admin", "No admin is available to review this SOS.");
        }

        if (!Enum.IsDefined(category))
        {
            throw new DomainException("sos.invalid_category", "Unknown SOS category.");
        }

        if (accuracyMeters is < 0 || (accuracyMeters is { } a && double.IsNaN(a)))
        {
            throw new DomainException("location.invalid_accuracy", "Location accuracy is not valid.");
        }

        if (clientCapturedAt > now + MaxFutureSkew || clientCapturedAt < now - MaxCaptureAge)
        {
            throw new DomainException("sos.invalid_capture_time", "Location timestamp is outside the accepted window.");
        }

        var sos = new SosRequest
        {
            Id = SequentialGuid.NewGuid(),
            ClientRequestId = clientRequestId,
            RequesterUserId = requester.Id,
            AssignedAdminId = assignedAdminId,
            Category = category,
            Description = Text.Optional(description, DescriptionMaxLength, nameof(Description)),
            Location = location.ToPoint(),
            Latitude = (decimal)location.Latitude,
            Longitude = (decimal)location.Longitude,
            AccuracyMeters = accuracyMeters,
            ClientCapturedAt = clientCapturedAt,
            Status = SosStatus.Pending,
        };

        sos._statusHistory.Add(SosStatusHistory.Create(sos.Id, null, SosStatus.Pending, requester.Id, null, now));

        if (!requester.SosRequiresApproval)
        {
            sos.TransitionTo(SosStatus.Approved, null, "Auto-approved: raised by an admin.", now);
            sos.IsAutoApproved = true;
            sos.ReviewedAt = now;
        }

        return sos;
    }

    public void Approve(Guid reviewerId, string? remarks, DateTime now)
    {
        EnsureAwaitingReview();
        var cleaned = Text.Optional(remarks, RemarksMaxLength, "Remarks");
        TransitionTo(SosStatus.Approved, reviewerId, cleaned, now);
        ReviewedByUserId = reviewerId;
        ReviewedAt = now;
        ReviewRemarks = cleaned;
    }

    public void Reject(Guid reviewerId, string remarks, DateTime now)
    {
        EnsureAwaitingReview();
        var cleaned = Text.Required(remarks, RemarksMaxLength, "Remarks");
        TransitionTo(SosStatus.Rejected, reviewerId, cleaned, now);
        ReviewedByUserId = reviewerId;
        ReviewedAt = now;
        ReviewRemarks = cleaned;
        ClosedAt = now;
    }

    /// <summary>Called by the escalation job when the assigned admin has not acted in time.</summary>
    public void Escalate(DateTime now)
    {
        if (Status != SosStatus.Pending)
        {
            return; // already handled - escalation is best-effort and idempotent
        }

        TransitionTo(SosStatus.Escalated, null, "No admin action within the escalation window.", now);
        EscalatedAt = now;
    }

    public void Cancel(Guid requesterId, string? reason, DateTime now)
    {
        if (requesterId != RequesterUserId)
        {
            throw new DomainException("sos.not_requester", "Only the person who raised the SOS can cancel it.");
        }

        TransitionTo(SosStatus.Cancelled, requesterId, Text.Optional(reason, RemarksMaxLength, "Reason"), now);
        ClosedAt = now;
    }

    public void Resolve(Guid userId, string? remarks, DateTime now)
    {
        TransitionTo(SosStatus.Resolved, userId, Text.Optional(remarks, RemarksMaxLength, "Remarks"), now);
        ClosedAt = now;
    }

    public void Expire(DateTime now)
    {
        TransitionTo(SosStatus.Expired, null, "Expired automatically.", now);
        ClosedAt = now;
    }

    /// <summary>
    /// Number of neighbours alerted. Maintained by dbo.usp_SelectSosRecipients on SQL Server; the
    /// non-SQL recipient selector (tests) sets it through this method.
    /// </summary>
    public void SetRecipientCount(int count) => RecipientCount = Math.Max(0, count);

    /// <summary>Set by the background reverse-geocoding job; failure to geocode never blocks an SOS.</summary>
    public void SetAddress(string? address) =>
        Address = string.IsNullOrWhiteSpace(address) ? null : Text.Truncate(address.Trim(), AddressMaxLength);

    public SosAttachment AddAttachment(Guid uploaderId, string blobName, string contentType, long sizeBytes, string sha256, int width, int height, DateTime now)
    {
        if (uploaderId != RequesterUserId)
        {
            throw new DomainException("sos.not_requester", "Only the person who raised the SOS can add photos.");
        }

        if (!IsOpen)
        {
            throw new DomainException("sos.closed", "Photos cannot be added to a closed SOS.");
        }

        if (_attachments.Count >= MaxAttachments)
        {
            throw new DomainException("sos.too_many_attachments", $"At most {MaxAttachments} photos are allowed.");
        }

        var attachment = SosAttachment.Create(Id, blobName, contentType, sizeBytes, sha256, width, height, now);
        _attachments.Add(attachment);
        return attachment;
    }

    private void EnsureAwaitingReview()
    {
        if (!IsAwaitingReview)
        {
            throw new DomainException("sos.already_reviewed", $"This SOS is already {Status}.");
        }
    }

    private void TransitionTo(SosStatus to, Guid? changedByUserId, string? remarks, DateTime now)
    {
        if (!AllowedTransitions.TryGetValue(Status, out var allowed) || !allowed.Contains(to))
        {
            throw new DomainException("sos.invalid_transition", $"An SOS cannot move from {Status} to {to}.");
        }

        var from = Status;
        Status = to;
        _statusHistory.Add(SosStatusHistory.Create(Id, from, to, changedByUserId, remarks, now));
    }
}
